"""
案例：演示  张量的索引操作

分类：
    简单行列索引
    列表索引
    范围索引
    布尔索引
    多维索引

掌握：
    简单行列索引，范围索引，多维索引
"""

# 导包
import torch

#1.设置随机种子
torch.manual_seed(24)

#2.创建随机张量.
t1 = torch.randint(1,10,(5,5))
print(t1)
print('-' * 30)

#3.演示张量的索引操作
#3.1 简单行列索引，格式：t1[行索引,列索引]
#获取第二行数据
print(t1[1])
print(t1[1,:]) #效果同上，这里的：表示所有列
print('-' * 30)
#3.2 列表索引 ,前边表示行，后边表示列，匹配时注意是第一个【x,y】,【z,w】,表示的是返回【x,z】,【y,w】的元素
#返回(0 , 1),(1 , 2)两个位置上的元素
print(t1[[0,1],[1,2]])
print(t1[[1,3],[2,4]]) #返回(1 , 2),(3 , 4)两个位置上的元素

#获取第0，1行的1，2列共4个元素
print(t1[[[0],[1]],[1,2]])
print('-' * 30)
#3.3 范围索引
# 前3行，前2列
print(t1[:3,:2])

#第二行到最后一行，前两列
print(t1[1:,:2])

#所有奇数行，偶数列
print(t1[1::2,::2])
print('-' * 30)

#3.4 布尔索引
#第3列，大于5的行数据
print(t1[t1[:,2]>5])

#第2行，大于5的列数据
print(t1[1][t1[1]>5])


#3.5 多维索引
#创建3维张量，即：2个3行4列的矩阵
t2 = torch.radint(1,10,(2,3,4))
print(f't2: {t2}')

#获取0轴上的第1个数据
print(t2[0,:,:])

#获取1轴上的第1个数据
print(t2[:,0,:])

#获取2轴上的第1个数据
print(t2[:,:,0])



