'''
案例：
    演示张量的拼接操作

涉及到的API:
    cat(): #不改变张量的维度，拼接张量，除了拼接的哪个维度，其他维度数必须相同
    stack(): #在指定维度上拼接张量，会改变维度数，所有的维度数必须相同
'''

#导包
import torch

#1.创建两个张量
t1 = torch.randint(1,10,(2,3))
t2 = torch.randint(1,10,(5,3))

#2.演示张量拼接
#2.1演示cat()函数
t3 = torch.cat((t1,t2),dim = 0) #拼接维度为0，即行方向，(2,3) + (2,3) = (4,3)
print(f't3:{t3}')

t4 = torch.cat((t1,t2),dim = 1) #拼接维度为1，即列方向，(2,3) + (2,3) = (2,6)
print(f't4:{t4}')

#2.2演示stack()函数
t5 = torch.stack((t1,t2),dim = 0) #拼接维度为0，即行方向，(2,3) + (2,3) = (2,2,3)
print(f't5:{t5}')
t6 = torch.stack((t1,t2),dim = 1) #拼接维度为1，即列方向，(2,3) + (2,3) = (2,2,3)
print(f't6:{t6}')
t7 = torch.stack((t1,t2),dim = 2) #拼接维度为2，即深度方向，(2,3) + (2,3) = (2,3,2)
print(f't7:{t7}')
